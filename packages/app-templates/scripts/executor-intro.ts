/**
 * Generate the MCP server instructions from the Executor app's `executor` skill, so the skill stays
 * their only source, and the digests telemetry uses to recognize the app's published skill files.
 * Hosts on every runtime import the results; Workers cannot read the files.
 * Pass --check to fail when a generated module is stale. Either way it fails when the skill names
 * an MCP SDK version other than the one `apps` is built with, which quick add pins, or when a skill
 * links a file the hosts do not publish in that skill, or when the entry skill or the authoring
 * router is longer than its limit in `lineLimits`. Before reading the skills it reads the fixture
 * trees in executor-intro-fixtures.ts, which it must publish or refuse.
 */
import * as NodeCrypto from "@effect/platform-node/NodeCrypto";
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import * as NodeServices from "@effect/platform-node/NodeServices";
import { Effect, FileSystem, Path, Schema } from "effect";
import { Digest } from "effect/crypto";
import { Hex } from "effect/encoding";
import apps from "apps/package.json" with { type: "json" };
import { fromMarkdown } from "mdast-util-from-markdown";
import { gfmFromMarkdown } from "mdast-util-gfm";
import { gfm } from "micromark-extension-gfm";
import { readSkillDocuments } from "../src/implementation/executor-skills.ts";
import { fixtures } from "./executor-intro-fixtures.ts";

class ExecutorIntroInvalid extends Schema.TaggedError<ExecutorIntroInvalid>()(
  "ExecutorIntroInvalid",
  { reason: Schema.String },
) {
  override get message() {
    return this.reason;
  }
}

interface MarkdownNode {
  readonly type: string;
  readonly url?: string;
  readonly children?: ReadonlyArray<MarkdownNode>;
}

/**
 * The destination of every link, image and link reference definition, as the parser reads it:
 * code is not a link, a title is not part of the target and `<...>` only delimits it.
 */
const linkTargets = (markdown: string): ReadonlyArray<string> => {
  const visit = (node: MarkdownNode): ReadonlyArray<string> => [
    ...(node.url !== undefined && ["link", "image", "definition"].includes(node.type)
      ? [node.url]
      : []),
    ...(node.children ?? []).flatMap(visit),
  ];
  return visit(
    fromMarkdown(markdown, { extensions: [gfm()], mdastExtensions: [gfmFromMarkdown()] }),
  );
};

/**
 * The skills under `skillsRoot` as the hosts publish them. Agents read a linked file through the
 * skill that links it, so every relative link must name a file the hosts publish in that skill.
 */
const publishedSkills = Effect.fnUntraced(function* (skillsRoot: string) {
  const documents = yield* readSkillDocuments(skillsRoot);
  const published = new Set<string>(documents.map(([file]) => file));
  const broken = documents.flatMap(([file, content]) => {
    const skill = file.split("/").slice(0, 2).join("/");
    return linkTargets(content)
      .filter((target) => !/^([a-z][a-z\d+.-]*:|#)/i.test(target))
      .filter((target) => {
        const resolved = decodeURIComponent(new URL(target, `file:///${file}`).pathname.slice(1));
        return !resolved.startsWith(`${skill}/`) || !published.has(resolved);
      })
      .map((target) => `${file.replace(/^skills\//, "")} links ${target}`);
  });
  if (broken.length > 0)
    return yield* new ExecutorIntroInvalid({
      reason: `Skill links must name a file in the same skill: ${broken.join("; ")}.`,
    });
  return documents;
});

/**
 * The most lines each short document may have. Every agent loads the entry skill into its
 * context, as the MCP server's instructions too, and every app author loads the router before the
 * topic it names, so each stays short and links the detail.
 */
const lineLimits = [
  { file: "skills/executor/SKILL.md", limit: 48, readers: "every agent loads it" },
  {
    file: "skills/app-authoring/SKILL.md",
    limit: 88,
    readers: "every app author loads it before the topic they need",
  },
] as const;

/** Lines of text, not counting the final newline. */
const lineCount = (content: string) => content.replace(/\n$/, "").split("\n").length;

const header = "// Generated by packages/app-templates/scripts/executor-intro.ts. Do not edit.";

NodeRuntime.runMain(
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const digest = yield* Digest.Digest;
    const root = yield* path.fromFileUrl(new URL("../", import.meta.url));
    const skill = yield* fs.readFileString(path.join(root, "executor/skills/executor/SKILL.md"));
    const body = /^---\n[\s\S]*?\n---\n([\s\S]+)$/.exec(skill)?.[1]?.trim();
    if (body === undefined || body === "")
      return yield* new ExecutorIntroInvalid({
        reason: "skills/executor/SKILL.md needs YAML frontmatter followed by a body.",
      });
    const sdk = apps.devDependencies["@modelcontextprotocol/sdk"];
    const integrations = yield* fs.readFileString(
      path.join(root, "executor/skills/app-authoring/integrations.md"),
    );
    if (/`@modelcontextprotocol\/sdk` \(currently\s+`([^`]+)`\)/.exec(integrations)?.[1] !== sdk)
      return yield* new ExecutorIntroInvalid({
        reason: `skills/app-authoring/integrations.md must name @modelcontextprotocol/sdk as (currently \`${sdk}\`), the version apps is built with.`,
      });
    const wrong = yield* Effect.forEach(fixtures, (fixture) =>
      Effect.scoped(
        Effect.gen(function* () {
          const directory = yield* fs.makeTempDirectoryScoped({ prefix: "executor-skills-" });
          for (const [file, contents] of Object.entries(fixture.files)) {
            const target = path.join(directory, file);
            yield* fs.makeDirectory(path.dirname(target), { recursive: true });
            if (typeof contents === "string") yield* fs.writeFileString(target, contents);
            else if ("bytes" in contents)
              yield* fs.writeFileString(target, "x".repeat(contents.bytes));
            else yield* fs.symlink(path.join(directory, contents.link), target);
          }
          const result = yield* Effect.result(publishedSkills(path.join(directory, "skills")));
          const outcome =
            result._tag === "Success"
              ? result.success.map(([file]) => file).sort()
              : result.failure.reason;
          const right =
            "published" in fixture
              ? JSON.stringify(outcome) === JSON.stringify([...fixture.published].sort())
              : typeof outcome === "string" && outcome.includes(fixture.refused);
          return right ? [] : [`${fixture.name}: ${JSON.stringify(outcome)}`];
        }),
      ),
    );
    if (wrong.flat().length > 0)
      return yield* new ExecutorIntroInvalid({
        reason: `The skill check is wrong about these fixtures (scripts/executor-intro-fixtures.ts): ${wrong.flat().join("; ")}.`,
      });
    const documents = yield* publishedSkills(path.join(root, "executor/skills"));
    const contents = new Map(documents);
    const long = lineLimits.flatMap(({ file, limit, readers }) => {
      const content = contents.get(file);
      if (content === undefined) return [`${file} is not published`];
      const lines = lineCount(content);
      return lines > limit
        ? [
            `${file} has ${lines} lines, ${lines - limit} over its limit of ${limit}: ${readers}. Move the detail into a skill or topic file it links, and keep one line pointing at it.`,
          ]
        : [];
    });
    if (long.length > 0) return yield* new ExecutorIntroInvalid({ reason: long.join(" ") });
    // The same files the hosts publish, keyed as a skill document names them.
    const digests = yield* Effect.forEach(
      // Code-point order, so the output does not depend on the machine's locale.
      [...documents].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
      ([file, content]) =>
        digest
          .digest(Digest.sha256, new TextEncoder().encode(content))
          .pipe(Effect.map((bytes) => [file.replace(/^skills\//, ""), Hex.encode(bytes)])),
    );
    const outputs = [
      {
        file: "executor-intro.gen.ts",
        content: `${header}

/** The body of skills/executor/SKILL.md, without its frontmatter. MCP servers send it as their instructions. */
export const executorIntro = ${JSON.stringify(body)};
`,
      },
      {
        file: "executor-skill-digests.gen.ts",
        content: `${header}

/** SHA-256 of each file the Executor app publishes as a skill, keyed by \`<skill>/<file>\`. */
export const executorSkillDigests: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(digests), null, 2)};
`,
      },
    ];
    for (const { file, content } of outputs) {
      const output = path.join(root, "src/implementation", file);
      if (!process.argv.includes("--check")) {
        yield* fs.writeFileString(output, content);
        continue;
      }
      const current = yield* fs.readFileString(output).pipe(Effect.orElseSucceed(() => ""));
      if (current !== content)
        return yield* new ExecutorIntroInvalid({
          reason: `${file} is stale. Run: bun run executor:intro`,
        });
    }
  }).pipe(Effect.provide([NodeServices.layer, NodeCrypto.layerDigest])),
);
