/**
 * Write the Homebrew formula for this release from its SHA256SUMS. The formula installs the same
 * release archive the install scripts use, for macOS and Linux on both architectures. Stable
 * releases update `executor`; beta releases update `executor-beta`, so a stable install never
 * moves to a beta.
 *
 * Usage: `node scripts/releases/homebrew.ts <SHA256SUMS> <tap directory>`
 */
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import * as NodeServices from "@effect/platform-node/NodeServices";
import { Console, Effect, FileSystem, Path, Schema } from "effect";
import { platformArchive, platforms, release } from "./config.ts";

class FormulaFailed extends Schema.TaggedError<FormulaFailed>()("FormulaFailed", {
  message: Schema.String,
}) {}

const program = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const [sums, tap] = process.argv.slice(2);
  if (sums === undefined || tap === undefined)
    return yield* new FormulaFailed({
      message: "Usage: homebrew.ts <SHA256SUMS> <tap directory>",
    });
  const name = release.channel === "beta" ? "executor-beta" : "executor";
  const output = path.join(tap, "Formula", `${name}.rb`);
  const listed = new Map<string, string>();
  for (const line of (yield* fs.readFileString(sums)).split("\n")) {
    const match = /^([0-9a-f]{64}) [ *](?:\.\/)?(.+)$/u.exec(line.trim());
    if (match?.[1] !== undefined && match[2] !== undefined) listed.set(match[2], match[1]);
  }
  const download = `https://github.com/${release.repository}/releases/download/${encodeURIComponent(release.tag)}`;
  const block = (os: "darwin" | "linux", arch: "arm64" | "x64") => {
    const target = platforms.find((entry) => entry.platform === os && entry.arch === arch);
    if (target === undefined) return Effect.fail(new FormulaFailed({ message: `${os}/${arch}` }));
    const file = platformArchive(target);
    const digest = listed.get(file);
    return digest === undefined
      ? Effect.fail(new FormulaFailed({ message: `${sums} does not list ${file}` }))
      : Effect.succeed(
          [
            `    ${arch === "arm64" ? "on_arm" : "on_intel"} do`,
            `      url "${download}/${file}"`,
            `      sha256 "${digest}"`,
            "    end",
          ].join("\n"),
        );
  };
  const formula = [
    "# Generated by scripts/releases/homebrew.ts in the Executor repository for each release.",
    `class ${release.channel === "beta" ? "ExecutorBeta" : "Executor"} < Formula`,
    '  desc "Run Executor locally and connect your agents to your apps"',
    `  homepage "${release.cloudOrigin}"`,
    `  version "${release.version}"`,
    '  license "MIT"',
    "",
    "  on_macos do",
    yield* block("darwin", "arm64"),
    yield* block("darwin", "x64"),
    "  end",
    "",
    "  on_linux do",
    yield* block("linux", "arm64"),
    yield* block("linux", "x64"),
    "  end",
    "",
    "  def install",
    "    # The executable finds the files beside it from its real path, through this symlink.",
    '    libexec.install Dir["*"]',
    '    bin.install_symlink libexec/"executor"',
    "  end",
    "",
    "  test do",
    '    assert_equal "executor v#{version}", shell_output("#{bin}/executor --version").strip',
    "  end",
    "end",
    "",
  ].join("\n");
  yield* fs.makeDirectory(path.dirname(output), { recursive: true });
  yield* fs.writeFileString(output, formula);
  yield* Console.log(`Wrote ${name} ${release.version} to ${output}`);
});

NodeRuntime.runMain(program.pipe(Effect.provide(NodeServices.layer)));
